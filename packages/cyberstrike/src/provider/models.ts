import { Global } from "../global"
import { Log } from "../util/log"
import path from "path"
import z from "zod"
import { Installation } from "../installation"
import { Flag } from "../flag/flag"
import { lazy } from "@/util/lazy"
import { isModelsCatalog, selectLocalModelsCatalog, shouldRefreshModels } from "./models-refresh"

// Try to import bundled snapshot (generated at build time)
// Falls back to undefined in dev mode when snapshot doesn't exist
/* @ts-ignore */

export namespace ModelsDev {
  const log = Log.create({ service: "models.dev" })
  const filepath = path.join(Global.Path.cache, "models.json")
  const refreshListeners = new Set<() => void | Promise<void>>()
  let refreshInFlight: Promise<void> | undefined

  export const Model = z.object({
    id: z.string(),
    name: z.string(),
    family: z.string().optional(),
    release_date: z.string(),
    attachment: z.boolean(),
    reasoning: z.boolean(),
    temperature: z.boolean(),
    tool_call: z.boolean(),
    interleaved: z
      .union([
        z.literal(true),
        z
          .object({
            field: z.enum(["reasoning", "reasoning_content", "reasoning_details"]),
          })
          .strict(),
      ])
      .optional(),
    cost: z
      .object({
        input: z.number(),
        output: z.number(),
        cache_read: z.number().optional(),
        cache_write: z.number().optional(),
        context_over_200k: z
          .object({
            input: z.number(),
            output: z.number(),
            cache_read: z.number().optional(),
            cache_write: z.number().optional(),
          })
          .optional(),
      })
      .optional(),
    limit: z.object({
      context: z.number(),
      input: z.number().optional(),
      output: z.number(),
    }),
    modalities: z
      .object({
        input: z.array(z.enum(["text", "audio", "image", "video", "pdf"])),
        output: z.array(z.enum(["text", "audio", "image", "video", "pdf"])),
      })
      .optional(),
    experimental: z
      .union([
        z.boolean(),
        z.object({
          modes: z
            .record(
              z.string(),
              z.object({
                cost: z
                  .object({
                    input: z.number().optional(),
                    output: z.number().optional(),
                    cache_read: z.number().optional(),
                  })
                  .optional(),
                provider: z
                  .object({
                    body: z.record(z.string(), z.any()).optional(),
                    headers: z.record(z.string(), z.string()).optional(),
                  })
                  .optional(),
              }),
            )
            .optional(),
        }),
      ])
      .optional(),
    status: z.enum(["alpha", "beta", "deprecated"]).optional(),
    options: z.record(z.string(), z.any()),
    headers: z.record(z.string(), z.string()).optional(),
    provider: z.object({ npm: z.string().optional(), api: z.string().optional() }).optional(),
    reasoning_options: z
      .array(
        z.union([
          z.object({ type: z.literal("effort"), values: z.array(z.string()) }),
          z.object({ type: z.literal("toggle") }),
          z.object({ type: z.literal("budget_tokens"), min: z.number().optional(), max: z.number().optional() }),
        ]),
      )
      .optional(),
    structured_output: z.boolean().optional(),
    variants: z.record(z.string(), z.record(z.string(), z.any())).optional(),
  })
  export type Model = z.infer<typeof Model>

  export const Provider = z.object({
    api: z.string().optional(),
    name: z.string(),
    env: z.array(z.string()),
    id: z.string(),
    npm: z.string().optional(),
    models: z.record(z.string(), Model),
  })

  export type Provider = z.infer<typeof Provider>

  function url() {
    return Flag.CYBERSTRIKE_MODELS_URL || "https://models.dev"
  }

  // Keep provider discovery local and predictable. Network refresh runs separately
  // so a slow or blocked models.dev request can never hold up CLI/TUI bootstrap.
  export const Data = lazy(async () => {
    const file = Bun.file(Flag.CYBERSTRIKE_MODELS_PATH ?? filepath)
    const cached = await file.json().catch(() => undefined)
    if (isModelsCatalog(cached)) return cached

    // @ts-ignore - generated by the production build; absent in source checkouts.
    const snapshot = await import("./models-snapshot")
      .then((m) => m.snapshot as Record<string, unknown>)
      .catch(() => undefined)

    return selectLocalModelsCatalog(cached, snapshot)
  })

  export async function get() {
    const result = await Data()
    return result as Record<string, Provider>
  }

  export function onRefresh(listener: () => void | Promise<void>) {
    refreshListeners.add(listener)
    return () => refreshListeners.delete(listener)
  }

  export function refresh(): Promise<void> {
    if (refreshInFlight) return refreshInFlight

    refreshInFlight = (async () => {
      const file = Bun.file(Flag.CYBERSTRIKE_MODELS_PATH ?? filepath)
      try {
        const response = await fetch(`${url()}/api.json`, {
          headers: {
            "User-Agent": Installation.USER_AGENT,
          },
          signal: AbortSignal.timeout(10 * 1000),
        })
        if (!response.ok) {
          throw new Error(`models.dev returned HTTP ${response.status}`)
        }

        const remoteData: unknown = await response.json()
        if (!isModelsCatalog(remoteData)) {
          throw new Error("models.dev returned an invalid catalogue payload")
        }

        const currentData = await file.json().catch(() => undefined)
        if (isModelsCatalog(currentData) && JSON.stringify(currentData) === JSON.stringify(remoteData)) return

        await Bun.write(file, JSON.stringify(remoteData))
        Data.reset()

        // Provider state is cached per project. Notify it only after the refreshed
        // catalogue is durable, so the first offline boot can recover on reconnect.
        for (const listener of [...refreshListeners]) {
          try {
            await listener()
          } catch (error) {
            log.error("Failed to apply refreshed models catalogue", { error })
          }
        }
      } catch (error) {
        // Refresh is best-effort; the cache/snapshot remains usable offline.
        log.debug("Could not refresh models.dev; continuing with local metadata", { error })
      }
    })().finally(() => {
      refreshInFlight = undefined
    })

    return refreshInFlight
  }
}

if (shouldRefreshModels(process.argv, Flag.CYBERSTRIKE_DISABLE_MODELS_FETCH)) {
  void ModelsDev.refresh()
  setInterval(
    () => {
      void ModelsDev.refresh()
    },
    60 * 1000 * 60,
  ).unref()
}
